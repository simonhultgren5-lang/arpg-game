-- Depths of Darkness game server: first PostgreSQL schema (0.5.0-beta.9).
-- Same tables as the SQLite database before it; times are milliseconds since 1970 (BIGINT).
-- Applied once by db.mjs (migrate), inside a transaction. Never edit an applied migration: add
-- migration-002-<name>.sql instead.

CREATE TABLE accounts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at    BIGINT NOT NULL,
  last_login_at BIGINT
);
-- Usernames are unique regardless of case ("alice" and "ALICE" are the same account).
CREATE UNIQUE INDEX accounts_username_ci ON accounts (lower(username));

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,              -- SHA-256 of the bearer token; the token itself is never stored
  account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX sessions_account ON sessions (account_id);
CREATE INDEX sessions_expires ON sessions (expires_at);

-- Up to 5 heroes per account (checked by the server under a lock on the account row), each with its
-- own save. data is the JSON object of save keys: "dod3d" is the game's progress; older "dod…" and
-- "mdjup" keys from the 2D game are kept beside it. legacy = the hero came from the one-save-per-account
-- days, so the desktop app keeps using the storage that hero already had on the PC.
CREATE TABLE characters (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  hero_class TEXT NOT NULL,
  color      TEXT NOT NULL,
  hero_level INTEGER NOT NULL DEFAULT 1,
  depth      INTEGER NOT NULL DEFAULT 1,
  data       TEXT,
  legacy     BOOLEAN NOT NULL DEFAULT false,
  created_at BIGINT NOT NULL,
  updated_at BIGINT
);
CREATE INDEX characters_account ON characters (account_id, created_at, id);

-- News posts and feature flags, set with admin.mjs. channel '' = every launcher.
CREATE TABLE news (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      TEXT NOT NULL,
  body       TEXT NOT NULL,
  channel    TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL
);
CREATE INDEX news_channel_created ON news (channel, created_at DESC);

CREATE TABLE flags (
  key        TEXT NOT NULL,
  channel    TEXT NOT NULL DEFAULT '',       -- a channel value wins over the one for everyone
  value      TEXT NOT NULL,                  -- JSON
  note       TEXT,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (key, channel)
);

-- Crash reports and usage events from launchers whose players opted in. Tied to a random install id,
-- never to an account. Usage events older than 90 days are deleted at startup.
CREATE TABLE crashes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at         BIGINT NOT NULL,
  source     TEXT NOT NULL,                  -- 'launcher' or 'game'
  version    TEXT,
  channel    TEXT,
  platform   TEXT,
  install_id TEXT,
  message    TEXT NOT NULL,
  detail     TEXT                            -- stack trace or the end of the game's log
);
CREATE INDEX crashes_at ON crashes (at);

CREATE TABLE telemetry (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at         BIGINT NOT NULL,
  install_id TEXT,
  version    TEXT,
  channel    TEXT,
  event      TEXT NOT NULL,
  props      TEXT                            -- JSON (cut at 2000 characters, so not always valid)
);
CREATE INDEX telemetry_at ON telemetry (at);
CREATE INDEX telemetry_event_at ON telemetry (event, at);

-- One row per SQLite database imported by db.mjs (importSqlite), so a file is never imported twice.
CREATE TABLE sqlite_imports (
  sha256      TEXT PRIMARY KEY,
  source      TEXT NOT NULL,
  imported_at BIGINT NOT NULL,
  counts      TEXT NOT NULL                  -- JSON: rows per table
);

-- props::jsonb that gives NULL instead of an error for text that isn't valid JSON (admin telemetry).
CREATE FUNCTION try_jsonb(t TEXT) RETURNS JSONB LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
  RETURN t::jsonb;
EXCEPTION WHEN others THEN
  RETURN NULL;
END
$$;
