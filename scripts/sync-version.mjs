// Copies the version from package.json into the game (game/js/00-version.js).
// package.json is the single source of truth — bump it with `npm run bump:patch|minor|major`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const target = path.join(root, 'game', 'js', '00-version.js');
const contents =
  `// Generated by scripts/sync-version.mjs from package.json. Do not edit by hand.\n` +
  `window.DOD_VERSION = ${JSON.stringify(version)};\n`;

// Compare without line endings: on Windows, git checks the file out with CRLF. Rewriting an unchanged
// version with LF would make git report a change, and `bun run release` would refuse to publish.
const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
if (current.replace(/\r\n/g, '\n') !== contents) {
  // Keep whichever line endings the file already uses.
  fs.writeFileSync(target, current.includes('\r\n') ? contents.replace(/\n/g, '\r\n') : contents);
  console.log(`Game version set to ${version}`);
}
